export function getLawId(title: string): string | undefined {
  if (!title) return undefined;

  const normalized = title.trim();
  if (lawMapping[normalized]) return lawMapping[normalized];

  const lowerNorm = normalized.toLowerCase();
  for (const [key, id] of Object.entries(lawMapping)) {
    if (key.toLowerCase() === lowerNorm) return id;
  }

  for (const [key, id] of Object.entries(lawMapping)) {
    const keyLower = key.toLowerCase();
    if (lowerNorm.includes(keyLower) || keyLower.includes(lowerNorm)) {
      return id;
    }
  }

  return undefined;
}

export function buildLawUrl(lawId: string): string | undefined {
  if (!lawId || !/^\d+$/.test(lawId)) return undefined;
  return `https://legalinfo.mn/mn/detail?lawId=${lawId}`;
}

export function buildLawUrlWithSword(lawId: string, sword: string): string | undefined {
  if (!lawId || !/^\d+$/.test(lawId)) return undefined;
  const base = `https://legalinfo.mn/mn/detail?lawId=${lawId}`;
  if (!sword || !sword.trim()) return base;
  return `${base}&sword=${encodeURIComponent(sword.trim())}`;
}

export function getLawUrl(title: string): string | undefined {
  const lawId = getLawId(title);
  if (!lawId) return undefined;
  return buildLawUrl(lawId);
}
