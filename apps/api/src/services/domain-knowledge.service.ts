export function scoreDomainCorpus(domain: QueryIntent, corpus: string): number {
  if (domain === 'unknown') {
    return 0;
  }

  const normalized = normalizeDomainText(corpus);
  return DOMAIN_KNOWLEDGE[domain].corpusPatterns.reduce(
    (score, pattern) => score + (pattern.test(normalized) ? 1 : 0),
    0,
  );
}

export function inferDomainFromKnowledgeCorpus(corpus: string): QueryIntent {
  let bestDomain: QueryIntent = 'unknown';
  let bestScore = 0;
  const normalized = normalizeDomainText(corpus);

  for (const domain of LEGAL_DOMAINS) {
    const score = scoreDomainCorpus(domain, normalized);
    if (score > bestScore) {
      bestScore = score;
      bestDomain = domain;
    }
  }

  return bestScore > 0 ? bestDomain : 'unknown';
}
