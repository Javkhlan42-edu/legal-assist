export const LEGAL_DOMAINS = Object.keys(DOMAIN_KNOWLEDGE) as LegalDomain[];

export function normalizeDomainText(text: string): string {
  return text.replace(/\s+/g, ' ').trim().toLowerCase();
}

function unique(values: string[]): string[] {
  return Array.from(new Set(values.filter(Boolean)));
}

export function getPreferredLawIds(domain: QueryIntent): string[] {
  if (domain === 'unknown') {
    return [];
  }

  return DOMAIN_KNOWLEDGE[domain].preferredLawIds;
}

export function getAllLegalKeywords(): string[] {
  return unique(LEGAL_DOMAINS.flatMap((domain) => DOMAIN_KNOWLEDGE[domain].legalKeywords));
}

export function getAllColloquialLegalKeywords(): string[] {
  return unique(LEGAL_DOMAINS.flatMap((domain) => DOMAIN_KNOWLEDGE[domain].colloquialKeywords));
}

export function getAllProtectedNonLegalPhrases(): string[] {
  return unique(
    LEGAL_DOMAINS.flatMap((domain) => DOMAIN_KNOWLEDGE[domain].protectedNonLegalPhrases ?? []),
  );
}

export function getAllLawHints(): string[] {
  return unique(LEGAL_DOMAINS.flatMap((domain) => DOMAIN_KNOWLEDGE[domain].lawHints));
}

